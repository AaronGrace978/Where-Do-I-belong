import type { ArchetypeId, City } from "../lib/types";
import { ARCHETYPES } from "../lib/types";

type Draft = {
  climate: string;
  languages?: string[];
  cost: number;
  jobs: string[];
  remoteFriendly?: boolean;
  scores: Partial<Record<ArchetypeId, number>>;
  people: string;
  environment: string;
  liveability: string;
  wikiTitle?: string;
};

function city(
  id: string,
  name: string,
  country: string,
  lat: number,
  lon: number,
  d: Draft,
): City {
  const scores = Object.fromEntries(
    ARCHETYPES.map((a) => [a, d.scores[a] ?? 38]),
  ) as Record<ArchetypeId, number>;
  return {
    id,
    name,
    country,
    lat,
    lon,
    climate: d.climate,
    languages: d.languages ?? ["English"],
    cost: d.cost,
    jobs: d.jobs,
    remoteFriendly: d.remoteFriendly ?? true,
    scores,
    people: d.people,
    environment: d.environment,
    liveability: d.liveability,
    wikiTitle: d.wikiTitle ?? name,
  };
}

